"""AST-based safety check for tool-command strings before exec().

The executor exec()s a command string to invoke a tool. That string is either
built deterministically by the executor (trusted, multi-statement, uses
json/os.path/glob) or generated by the LLM (untrusted). A strict "only
`execution = tool.execute(...)`" whitelist would reject the legitimate
deterministic commands, so this validator instead **denies dangerous
capabilities** while allowing ordinary orchestration code:

Rejected:
  - importing dangerous modules (subprocess, sys, socket, shutil, ctypes,
    importlib, pickle, urllib, requests, ...);
  - calls to eval / exec / compile / __import__ / open / input / globals /
    locals / vars / getattr / setattr / delattr;
  - dangerous os.* calls (system, popen, remove, exec*, spawn*, fork, kill, ...);
  - any attribute access to subprocess.* / sys.* / socket.* / ctypes.*;
  - dunder attribute access (__class__, __globals__, __subclasses__, ...) used
    for sandbox escapes.

IMPORTANT -- this is NOT a security sandbox. It is a best-effort deny-list that
raises the bar against the obvious destructive/RCE patterns. A determined command
using *allowed* libraries can still perform I/O (e.g. ``pandas.read_csv``,
``numpy.load``, ``open`` is blocked but ``pathlib`` methods are partially blocked
by attr name only). Do NOT rely on this to safely run untrusted code. The real
isolation paths are:
  - ``Executor.run_managed_tool`` (deterministic, no exec) for managed tools;
  - running genuinely untrusted code in a separate process/container (as the
    Python_Code_Generator_Tool now does via subprocess with a hard timeout).
"""

from __future__ import annotations

import ast

ALLOWED_IMPORT_ROOTS = {
    "json", "os", "glob", "re", "math", "numpy", "pandas", "time", "uuid",
    "traceback", "collections", "itertools", "functools", "copy", "datetime",
    "pathlib", "warnings", "string", "statistics", "random",
}

BANNED_CALL_NAMES = {
    "eval", "exec", "compile", "__import__", "open", "input", "breakpoint",
    "globals", "locals", "vars", "getattr", "setattr", "delattr", "memoryview",
}

DANGEROUS_MODULE_ATTRS = {
    "subprocess", "sys", "socket", "ctypes", "importlib", "multiprocessing",
    "pickle", "marshal", "urllib", "requests", "shutil", "pty", "signal",
}

DANGEROUS_OS_ATTRS = {
    "system", "popen", "remove", "unlink", "rmdir", "removedirs", "rename",
    "renames", "chmod", "chown", "fork", "kill", "killpg", "putenv", "startfile",
    "abort", "_exit", "execv", "execve", "execvp", "execvpe", "execl", "execle",
    "execlp", "spawnv", "spawnve", "spawnl", "spawnle",
}

# File/dir access method names banned regardless of receiver (catches pathlib
# Path.read_text/write_text, os.listdir/walk/scandir, shutil.rmtree/copy*, ...).
# NOTE: generic reader names like `load`/`read_csv` are intentionally NOT here --
# banning them would break legitimate use and still wouldn't make this a sandbox.
BANNED_FILE_ATTRS = {
    "read_text", "write_text", "read_bytes", "write_bytes",
    "listdir", "scandir", "walk", "makedirs", "mkdir", "rmtree",
    "copytree", "copyfile", "copy2", "move",
}

BANNED_ATTRS = DANGEROUS_OS_ATTRS | BANNED_FILE_ATTRS


def _is_dunder(name: str) -> bool:
    return name.startswith("__") and name.endswith("__")


def validate_command(command: str) -> tuple[bool, str]:
    """Return (ok, reason). `ok` is False with a human reason when unsafe."""
    if not isinstance(command, str) or not command.strip():
        return False, "empty command"
    try:
        tree = ast.parse(command)
    except SyntaxError as e:
        return False, f"syntax error: {e}"

    for node in ast.walk(tree):
        if isinstance(node, ast.Import):
            for alias in node.names:
                root = alias.name.split(".")[0]
                if root not in ALLOWED_IMPORT_ROOTS:
                    return False, f"disallowed import: {alias.name}"
        elif isinstance(node, ast.ImportFrom):
            root = (node.module or "").split(".")[0]
            if root not in ALLOWED_IMPORT_ROOTS:
                return False, f"disallowed import-from: {node.module}"
            # `from os import system/listdir/...` would otherwise leak a dangerous
            # callable that is then called by bare name (not an attribute access)
            for alias in node.names:
                if alias.name in BANNED_ATTRS:
                    return False, f"disallowed import-from: {node.module}.{alias.name}"
        elif isinstance(node, ast.Call):
            func = node.func
            if isinstance(func, ast.Name) and func.id in BANNED_CALL_NAMES:
                return False, f"disallowed call: {func.id}()"
        elif isinstance(node, ast.Attribute):
            if _is_dunder(node.attr):
                return False, f"disallowed dunder access: .{node.attr}"
            # dangerous attr name regardless of receiver (defeats os/o aliasing
            # and catches pathlib/shutil file ops)
            if node.attr in BANNED_ATTRS:
                return False, f"disallowed call: .{node.attr}"
            value = node.value
            if isinstance(value, ast.Name) and value.id in DANGEROUS_MODULE_ATTRS:
                return False, f"disallowed access: {value.id}.{node.attr}"
        elif isinstance(node, ast.Name):
            if node.id in DANGEROUS_MODULE_ATTRS:
                # bare reference to a dangerous module (e.g. assigned from import)
                return False, f"disallowed module reference: {node.id}"

    return True, ""
